def kalman_hedge_ratio(price_y, price_x, delta=1e-5):
    """
    Estimate time-varying hedge ratio via Kalman filter.
    price_y = beta_t * price_x + spread_t
    """
    n = len(price_y)

    # Observation matrix changes each timestep: [price_x, 1] for the regression [beta, intercept]
    obs_mat = np.vstack([price_x, np.ones(n)]).T[:, np.newaxis, :]

    kf = KalmanFilter(
        n_dim_obs=1,
        n_dim_state=2,               # [beta, intercept]
        initial_state_mean=[0, 0],
        initial_state_covariance=np.ones((2, 2)),
        transition_matrices=np.eye(2),
        observation_matrices=obs_mat,
        observation_covariance=1.0,
        transition_covariance=delta / (1 - delta) * np.eye(2)
    )

    state_means, state_covs = kf.filter(price_y.values)
    beta_t = state_means[:, 0]     # time-varying hedge ratio
    intercept_t = state_means[:, 1]

    spread = price_y.values - (beta_t * price_x.values + intercept_t)
    return beta_t, intercept_t, spread

