def compute_ticker_exposure(pair, position_size_t, signal_t, beta_t):
    """
    For a pair (A, B) with hedge ratio beta, being long the spread means
    long A, short beta*B (or vice versa if short the spread).
    Returns dollar exposure attributed to each individual ticker.
    """
    t1, t2 = pair
    exposure_1 = signal_t * position_size_t
    exposure_2 = -signal_t * position_size_t * beta_t
    return {t1: exposure_1, t2: exposure_2}

# Aggregate exposure across ALL pairs, by ticker, for a given day
def aggregate_daily_exposure(date, kalman_results, signals, position_sizes):
    ticker_exposure = {}
    for pair in kalman_results:
        idx = log_prices.index.get_loc(date)
        signal_t = signals[pair]["signal"].iloc[idx]
        if signal_t == 0:
            continue
        size_t = position_sizes[pair].iloc[idx]
        beta_t = kalman_results[pair]["beta"][idx]
        exp = compute_ticker_exposure(pair, size_t, signal_t, beta_t)
        for ticker, val in exp.items():
            ticker_exposure[ticker] = ticker_exposure.get(ticker, 0) + val
    return ticker_exposure

