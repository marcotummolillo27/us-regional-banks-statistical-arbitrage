def test_cointegration(price_1, price_2):
    """Test cointegration in both directions, return the better result."""
    results = {}
    for direction, (y, x) in [("1_on_2", (price_1, price_2)), ("2_on_1", (price_2, price_1))]:
        x_with_const = sm.add_constant(x)
        model = sm.OLS(y, x_with_const).fit()
        beta = model.params.iloc[1]
        residuals = model.resid
        adf_stat, p_value, _, _, crit_values, _ = adfuller(residuals, autolag="AIC")
        results[direction] = {
            "beta": beta,
            "adf_stat": adf_stat,
            "p_value": p_value,
            "residuals": residuals
        }
    # Pick the direction with the lower p-value (stronger evidence of stationarity)
    best_direction = min(results, key=lambda d: results[d]["p_value"])
    return best_direction, results[best_direction]

