def generate_zscore_signal(spread, index, lookback=63, entry_z=2.0, exit_z=0.5, stop_z=4.0):
    spread_series = pd.Series(spread, index=index)   # <-- fix: pass the real index
    rolling_mean = spread_series.rolling(lookback).mean()
    rolling_std = spread_series.rolling(lookback).std()
    zscore = (spread_series - rolling_mean) / rolling_std

    signal = pd.Series(0, index=spread_series.index)
    position = 0

    for t in range(lookback, len(zscore)):
        z = zscore.iloc[t]
        if position == 0:
            if z > entry_z:
                position = -1
            elif z < -entry_z:
                position = 1
        elif position == 1:
            if z >= -exit_z or z < -stop_z:
                position = 0
        elif position == -1:
            if z <= exit_z or z > stop_z:
                position = 0
        signal.iloc[t] = position

    return zscore, signal

