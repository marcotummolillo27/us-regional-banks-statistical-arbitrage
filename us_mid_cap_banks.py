def compute_position_sizes(kalman_results, signals, lookback=63, target_risk=1.0):
    """
    Size each pair's position inversely to its rolling spread volatility,
    so each active pair contributes roughly equal risk.
    """
    sizes = {}
    for pair, result in kalman_results.items():
        spread_series = pd.Series(result["spread"], index=log_prices.index)
        rolling_vol = spread_series.rolling(lookback).std()
        # Inverse-vol sizing: lower vol -> larger position, higher vol -> smaller
        size = target_risk / rolling_vol
        sizes[pair] = size
    return sizes

